  await expect(page.locator('header[data-window-drag]')).toContainText('hi')
  await expect(editor(page)).toHaveAttribute('contenteditable', 'false')
  await expect(page.getByText('Read-only conversation', { exact: true })).toBeVisible()
  await expect(page.getByText('Hi! How can I help you today?', { exact: true })).toBeVisible()
  if (capture) await page.screenshot({ animations: 'disabled', path: 'test-results/story-mode/example.png' })
  const example = (await call(page, 'papermoon-story/state', {})).example
  const refused = await rpc(page, 'session/prompt', { args: { request: { sessionId: example.id, requestId: crypto.randomUUID(), content: [{ type: 'text', text: 'do not send' }] } } })
  expect(refused.ok).toBe(false)
  await next(page).click()
  await atStep(page, 3)
  await expect(page.getByRole('tab', { name: 'Chat', exact: true })).toHaveAttribute('aria-selected', 'true')
  await expect(next(page)).toBeDisabled()
  await expect(page.locator('.pm-guidance-hint')).toBeVisible()
  await page.getByRole('button', { name: 'Plugins', exact: true }).click()
  await expect(page.locator('.pm-guidance-hint')).toHaveCount(0)
  await expect(next(page)).toBeDisabled()
  await expect(page.getByRole('switch', { name: 'Enable Story Mode', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'New session', exact: true }).last().click()
  await expect(page.locator('.pm-guidance-hint')).toBeVisible()
  const tab = page.getByRole('tab', { name: 'Trajectory', exact: true })
  const target = await tab.boundingBox()
  const highlight = await page.locator('.pm-guidance-outline').boundingBox()
  expect(highlight!.x).toBeCloseTo(target!.x - 4)
  expect(highlight!.width).toBeCloseTo(target!.width + 8)
  if (capture) {
    await page.screenshot({ animations: 'disabled', path: 'test-results/story-mode/hint.png' })
    const viewport = page.viewportSize()!
    await page.setViewportSize({ width: 390, height: 844 })
    let previousX = Number.NaN
    let stableFrames = 0
    await expect.poll(async () => {
      const x = (await tab.boundingBox())?.x ?? 999
      stableFrames = x < 200 && Math.abs(x - previousX) < 0.1 ? stableFrames + 1 : 0
      previousX = x
      return stableFrames
    }, { intervals: [100] }).toBeGreaterThanOrEqual(2)
    await expect(page.locator('.pm-guidance-hint')).toBeVisible()
    await expect.poll(async () => {
      const anchor = await tab.boundingBox()
      const ring = await page.locator('.pm-guidance-outline').boundingBox()
      return anchor && ring ? Math.abs(ring.x - anchor.x + 4) : 100
    }).toBeLessThan(1)
    await expect.poll(async () => {
      const hint = await page.locator('.pm-guidance-hint').boundingBox()
      return hint ? hint.x + hint.width : 999
    }).toBeLessThanOrEqual(390)
    await page.screenshot({ animations: 'disabled', path: 'test-results/story-mode/hint-narrow.png' })
    await page.setViewportSize(viewport)
  }
  await page.keyboard.press('Escape')
  await expect(page.locator('.pm-guidance-hint')).toHaveCount(0)
  await expect(next(page)).toBeDisabled()
  await page.getByRole('button', { name: 'Show hint', exact: true }).click()
  await expect(page.locator('.pm-guidance-hint')).toBeVisible()
  // Native keyboard activation, not an overlay click or a chapter-generated navigation.
  await tab.focus()
  await page.keyboard.press('Enter')
  await expect(tab).toHaveAttribute('aria-selected', 'true')
  await expect(page.locator('[data-conversation-content]')).toContainText('Initial System Prompt')
  await expect(next(page)).toBeEnabled()
  await expect(page.locator('.pm-guidance-hint')).toHaveCount(0)
