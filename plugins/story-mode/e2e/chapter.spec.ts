async function rpc(page: Page, name: string, payload: unknown) {
  const response = await page.request.post(new URL('/api/' + name, server.url).href, { data: { type: 'client-request', rpcId: crypto.randomUUID(), method: name, payload } })
  return (await response.json()).result
}
async function call(page: Page, name: string, payload: unknown) { const result = await rpc(page, name, payload); expect(result.ok, JSON.stringify(result)).toBe(true); return result.value }
function requests() { const path = join(server.directory, 'data/requests.jsonl'); return existsSync(path) ? readFileSync(path, 'utf8').trim().split('\n').map(line => JSON.parse(line)).filter(value => !value.purpose) : [] }
const guide = (page: Page) => page.locator('.pm-story-guide:visible')
const next = (page: Page) => guide(page).getByRole('button', { name: 'Continue', exact: true })
async function select(page: Page, label: string, choice: string) { await page.getByRole('button', { name: label, exact: true }).click(); await page.getByRole('menuitem', { name: choice, exact: true }).click() }
async function section(page: Page, index: number) { await expect(guide(page)).toHaveAttribute('data-story-section', String(index)) }
async function enter(page: Page, dismissHint = false) {
  await page.goto(server.url)
  const notice = page.getByRole('dialog', { name: 'Internal Testing Notice', exact: true })
  await notice.getByRole('button', { name: 'Continue', exact: true }).click()
  await page.getByRole('button', { name: 'Story Mode', exact: true }).click()
  await page.getByRole('textbox', { name: 'Save name', exact: true }).fill('Keeper')
  if (dismissHint) await page.screenshot({ path: 'test-results/story-mode/save-entrance.png' })
  await page.getByRole('button', { name: 'Create save', exact: true }).click()
  await expect(guide(page)).toHaveCount(0)
  await expect(page.locator('.pm-guidance-hint')).toContainText('Save created. Open the right sidebar here to view Story Guide.')
  await expect(page.locator('.pm-guidance')).toHaveAttribute('data-guidance-target', '[data-sidebar-right-expand]')
  if (dismissHint) {
    await page.screenshot({ path: 'test-results/story-mode/creation-hint.png' })
    await page.keyboard.press('Escape')
    await expect(page.locator('.pm-guidance-hint')).toHaveCount(0)
    await expect(guide(page)).toHaveCount(0)
  }
  await page.getByRole('button', { name: 'Open right sidebar', exact: true }).click()
  await section(page, 1)
  await expect(page.locator('.pm-guidance-hint')).toHaveCount(0)
  return (await call(page, 'papermoon-story/list', {}))[0].id as string
}
