test('later replies do not satisfy viewing the first successful trajectory', async ({ page }) => {
  await reachPractice(page)
  for (let index = 0; index < 8; index++) {
    await send(page, `message ${index}`)
    await expect.poll(() => requests().length).toBe(index + 1)
    await expect(page.getByRole('button', { name: 'Stop generating', exact: true })).toBeHidden()
  }
  await atStep(page, 5)
  const before = await call(page, 'papermoon-story/state', {})
  expect(before.attempt.successfulTurn).toBe(1)
  const firstReply = before.conversation.events.findLast((event: { type: string; data: { turn: number } }) => event.type === 'assistant/message' && event.data.turn === 1)
  await page.getByRole('tab', { name: 'Trajectory', exact: true }).click()
  await expect(page.locator('[data-conversation-view=trajectory] [data-trajectory-scroll]')).toBeVisible()
  // The native ledger initially shows its tail. Later visible replies cannot acknowledge the first one.
  await expect(page.getByRole('button', { name: 'Complete chapter', exact: true })).toBeDisabled()
  expect((await call(page, 'papermoon-story/state', {})).attempt.trajectorySeen).toBe(false)
  await page.locator('[data-trajectory-scroll]').evaluate(element => element.scrollTo({ top: 0 }))
  await page.locator(`[data-kind=message][data-source-seq="${firstReply.seq}"]`).scrollIntoViewIfNeeded()
  await expect(page.getByRole('button', { name: 'Complete chapter', exact: true })).toBeEnabled()
  expect((await call(page, 'papermoon-story/state', {})).attempt.successfulTurn).toBe(1)
})
