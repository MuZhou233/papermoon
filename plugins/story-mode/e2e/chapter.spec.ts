test('collapsed reminders, keyboard hints, save isolation and empty openings preserve progress', async ({ page }) => {
  const id = await enter(page)
  await page.getByRole('button', { name: 'Collapse right sidebar', exact: true }).click()
  await expect(guide(page)).toHaveCount(0)
  const current = await call(page, 'papermoon-story/state', { playbookId: id })
  await call(page, 'papermoon-story/advance', { playbookId: id, section: 1, expectedSequence: current.sequence })
  await expect(page.getByRole('button', { name: 'Progress updated', exact: true })).toBeVisible()
  await expect(guide(page)).toHaveCount(0)
  await page.getByRole('button', { name: 'Progress updated', exact: true }).click()
  await section(page, 2)
  await expect(page.getByRole('button', { name: 'Progress updated', exact: true })).toHaveCount(0)
  await page.setViewportSize({ width: 390, height: 844 })
  await guide(page).getByRole('button', { name: 'Show me where', exact: true }).click()
  await expect(guide(page)).toHaveCount(0)
  await expect(page.locator('.pm-guidance-hint')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.locator('.pm-guidance-hint')).toHaveCount(0)
  await page.getByRole('button', { name: 'Save draft', exact: true }).click()
  await page.getByRole('button', { name: 'Open right sidebar', exact: true }).click()
  await section(page, 2)
  await expect(page.locator('[data-story-unlock="opening"]')).toHaveCount(0)
  await expect(next(page)).toBeEnabled(); await next(page).click(); await section(page, 3)
  await expect(next(page)).toBeDisabled()
  const first = await call(page, 'papermoon-story/state', { playbookId: id })
  const second = await call(page, 'papermoon-story/create', { name: 'Second', projectId: first.playbook.projectId, storyline: 'fogbound-earthshine', language: 'en' })
  expect((await call(page, 'papermoon-story/state', { playbookId: second.id })).progress.section).toBe(1)
  expect((await call(page, 'papermoon/snapshot', { ref: { kind: 'draft', playbookId: id } })).content.opening.messages).toEqual([])
  const denied = await rpc(page, 'papermoon/save', { playbookId: second.id, expectedSequence: 0, operations: [{ kind: 'set-system-prompt', text: 'too early' }] })
  expect(denied.ok).toBe(false)
  expect(requests()).toHaveLength(0)
})

